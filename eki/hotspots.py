"""Files many items write — the plan's hot spots (README 'Repository hygiene
decides how parallel a project can be').

A file in HOT_AT or more items' write-sets, or a tracked file the build
rewrites, makes parallel items collide. The planner warns about them on the
goal and can put an item that splits them ahead of the rest. Pure, apart from
the two git readers at the bottom.
"""
from __future__ import annotations

import fnmatch
import re
import subprocess
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

HOT_AT = 3
SPLIT_TITLE = "Split the shared files first"

_GLOB = re.compile(r"[*?\[]")
_BUILD = re.compile(r"(?<![\w/.-])(build|make|tsc|webpack|gradle|gradlew)(?![\w/.-])")


def _includes(entries: List[str], file: str) -> bool:
    return any(e == file or fnmatch.fnmatch(file, e) for e in entries)


def find(planned: List[Dict[str, Any]], generated: List[str]) -> List[Dict[str, Any]]:
    """The hot spots: [{file, items, generated}], most items first."""
    gen = set(generated or [])
    candidates: List[str] = []
    for it in planned:
        for e in it.get("files") or []:
            if not _GLOB.search(e) and e not in candidates:
                candidates.append(e)
    for g in generated or []:
        if g not in candidates:
            candidates.append(g)
    spots = []
    for f in candidates:
        items = [it.get("title", "") for it in planned if _includes(it.get("files") or [], f)]
        if len(items) >= HOT_AT or f in gen:
            spots.append({"file": f, "items": items, "generated": f in gen})
    return sorted(spots, key=lambda s: (-len(s["items"]), s["file"]))


def warning(spot: Dict[str, Any]) -> str:
    n = len(spot.get("items") or [])
    if spot.get("generated"):
        text = (f"{spot['file']} is generated by the build and tracked in git"
                " — untrack it first, or every item will conflict")
        return text + (f" (in {n} items)" if n else "")
    return f"{spot['file']} is in {n} items — split it first, or they will conflict"


def split_item(spots: List[Dict[str, Any]]) -> Dict[str, Any]:
    """The proposed first item, in selfbrief.items_in's shape."""
    shared = [s["file"] for s in spots if not s.get("generated")]
    generated = [s["file"] for s in spots if s.get("generated")]
    parts = []
    if shared:
        parts.append("Split each shared file into one file per part, with the build or "
                     "loader joining them, so the items can each touch their own part: "
                     + ", ".join(shared) + ".")
    if generated:
        parts.append("Untrack each generated file (git rm --cached, add it to .gitignore, "
                     "let the build make it): " + ", ".join(generated) + ".")
    parts.append("Keep behaviour the same and the check green.")
    files = [s["file"] for s in spots] + ([".gitignore"] if generated else [])
    return {"title": SPLIT_TITLE, "spec": " ".join(parts), "files": files,
            "deps": [], "independent": False}


def ahead(planned: List[Dict[str, Any]], spots: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """The plan with the split item first and every other item depending on it."""
    if not spots:
        return planned
    rest = []
    for it in planned:
        copy = dict(it)
        deps = list(it.get("deps") or [])
        if SPLIT_TITLE not in deps:
            deps.append(SPLIT_TITLE)
        copy["deps"] = deps
        rest.append(copy)
    return [split_item(spots)] + rest


def _git(worktree: Union[str, Path], *args: str) -> Optional[List[str]]:
    try:
        r = subprocess.run(["git", "-C", str(worktree), *args],
                           capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return None
    if r.returncode != 0:
        return None
    return [line for line in r.stdout.splitlines() if line]


def listed_generated(worktree: Union[str, Path]) -> List[str]:
    """Tracked files the worktree's .gitignore rules ignore."""
    out = _git(worktree, "ls-files", "-c", "-i", "--exclude-standard")
    return sorted(set(out or []))


def rewritten(worktree: Union[str, Path]) -> List[str]:
    """Tracked files a build changed or deleted (against HEAD)."""
    if not Path(worktree).is_dir():
        return []
    out = _git(worktree, "diff", "--name-only", "HEAD")
    return sorted(set(out or []))


def builds(cmd: Optional[str]) -> bool:
    """Whether a check command line runs a build step."""
    return bool(cmd) and bool(_BUILD.search(cmd))
