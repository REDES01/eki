"""The plan's hot spots: files many items write (eki/hotspots.py)."""
from eki import hotspots, workspace


def item(title, *files, deps=()):
    return {"title": title, "spec": "do " + title, "files": list(files),
            "deps": list(deps), "independent": not deps}


def test_a_file_in_four_items_is_hot():
    plan = [item("A", "q.json", "a.py"), item("B", "q.json", "b.py"),
            item("C", "q.json"), item("D", "q.json", "a.py")]
    assert hotspots.find(plan, []) == [
        {"file": "q.json", "items": ["A", "B", "C", "D"], "generated": False}]


def test_a_file_in_two_items_is_not_hot():
    assert hotspots.find([item("A", "x.py"), item("B", "x.py"), item("C", "y.py")], []) == []


def test_a_glob_entry_counts_for_the_file():
    plan = [item("A", "data/q.json"), item("B", "data/*.json"), item("C", "data/q.json")]
    assert hotspots.find(plan, []) == [
        {"file": "data/q.json", "items": ["A", "B", "C"], "generated": False}]


def test_a_generated_file_is_hot_with_no_items():
    spots = hotspots.find([item("A", "a.py")], ["story.gen.json"])
    assert spots == [{"file": "story.gen.json", "items": [], "generated": True}]


def test_sorted_by_items_then_name():
    plan = [item(t, "b.json", "a.json", *(["z.json"] if t != "D" else [])) for t in "ABCD"]
    assert [s["file"] for s in hotspots.find(plan, [])] == ["a.json", "b.json", "z.json"]


def test_warning_texts():
    assert hotspots.warning({"file": "q.json", "items": list("ABCDEFG"), "generated": False}) \
        == "q.json is in 7 items — split it first, or they will conflict"
    assert hotspots.warning({"file": "s.js", "items": [], "generated": True}) == (
        "s.js is generated by the build and tracked in git"
        " — untrack it first, or every item will conflict")
    assert hotspots.warning({"file": "s.js", "items": ["A", "B"], "generated": True}) == (
        "s.js is generated by the build and tracked in git"
        " — untrack it first, or every item will conflict (in 2 items)")


def test_split_item_names_the_files():
    s = hotspots.split_item([{"file": "q.json", "items": list("ABC"), "generated": False},
                             {"file": "s.js", "items": [], "generated": True}])
    assert s["title"] == hotspots.SPLIT_TITLE
    assert s["files"] == ["q.json", "s.js", ".gitignore"]
    assert s["deps"] == [] and s["independent"] is False
    assert "q.json" in s["spec"] and "git rm --cached" in s["spec"]
    assert ".gitignore" not in hotspots.split_item(
        [{"file": "q.json", "items": list("ABC"), "generated": False}])["files"]


def test_ahead_puts_the_split_first():
    plan = [item(t, "q.json") for t in "ABCD"]
    plan[1]["deps"] = ["A"]
    spots = hotspots.find(plan, [])
    out = hotspots.ahead(plan, spots)
    assert out[0]["title"] == hotspots.SPLIT_TITLE
    assert [i["title"] for i in out[1:]] == ["A", "B", "C", "D"]
    assert all(hotspots.SPLIT_TITLE in i["deps"] for i in out[1:])
    assert out[2]["deps"] == ["A", hotspots.SPLIT_TITLE]
    assert plan[0]["deps"] == [] and plan[1]["deps"] == ["A"]      # not mutated


def test_ahead_without_spots_is_unchanged():
    plan = [item("A", "a.py"), item("B", "b.py")]
    assert hotspots.ahead(plan, hotspots.find(plan, [])) is plan


def test_listed_generated(proj):
    (proj / "dist").mkdir()
    (proj / "dist" / "out.js").write_text("built\n")
    workspace.git(proj, "add", "dist/out.js")
    workspace.git(proj, "commit", "-q", "-m", "built output")
    (proj / ".gitignore").write_text("dist/\n")
    assert hotspots.listed_generated(proj) == ["dist/out.js"]
    assert hotspots.listed_generated(proj / "nowhere") == []


def test_rewritten(proj, tmp_path):
    assert hotspots.rewritten(proj) == []
    (proj / "app.py").write_text("print('built')\n")
    (proj / "README.md").unlink()
    (proj / "new.txt").write_text("untracked\n")
    assert hotspots.rewritten(proj) == ["README.md", "app.py"]
    assert hotspots.rewritten(tmp_path / "missing") == []
    (tmp_path / "plain").mkdir()
    assert hotspots.rewritten(tmp_path / "plain") == []


def test_builds():
    for cmd in ("npm run build", "cargo build --release", "go build ./...", "vite build",
                "make", "make test", "npx tsc --noEmit", "webpack", "gradle check",
                "bin/check && npm run build"):
        assert hotspots.builds(cmd), cmd
    for cmd in (None, "", "bin/check", "pytest", "pytest tests/test_build.py", "bin/make-x"):
        assert not hotspots.builds(cmd), cmd
